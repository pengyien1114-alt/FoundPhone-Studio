const voices = [
  "ㅇㅇ",
  "익명",
  "原PO",
  "回放組",
  "眼神偵探下班了",
  "先吃完再嗑",
  "今天不站穩",
];
function thread(start: number, lines: string[]) {
  return lines
    .map(
      (text, i) =>
        `${start + i}樓｜${voices[(start + i) % voices.length]}\n${text}`,
    )
    .join("\n\n");
}
