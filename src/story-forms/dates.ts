import type { Runtime, Work } from "../schema";

export function dateValues(
  work: Work,
  state: Runtime,
  facts: Record<string, string>,
) {
  const rules = work.data.notes.find(
    (i) => i.id === "relationship-rules",
  )?.meta;
  const result: Record<string, string> = {};
  const together = facts.mutualSuccess === "true";
  result.dateOpening13 = together
    ? `你和 ${facts.mutualTarget} 在河邊的小攤各買了一杯熱飲。沒有任務卡可以借題發揮，想聊什麼反而都得自己開口。他問你還記不記得第一次坐在同一張桌子的時候，兩個人當時都在忙著假裝鎮定。你記得的畫面和他不一樣；他笑著說自己那時候連水喝完了都沒發現。走到長椅前，你們各留一點空位，沒有因為互選就自動把所有距離取消。`
    : "你把原本準備帶出門的外套掛回去。客廳裡還有其他人，各自沒有解釋自己的結果。有人問要不要一起煮午餐，你看見桌上還有沒洗完的菜；今天留下來的時間仍然屬於你，不需要全用來猜對方為什麼沒選。";
  result.dateQuestion13a = together
    ? "他問你，今天為什麼願意再選一次他？"
    : "沒有約會的這段時間，你想怎樣過？";
  result.dateQuestion13b = together
    ? "回去前，他問今天有沒有哪件事，讓你想像節目外的相處。你想怎樣回答？"
    : "到了下午，你想把今天留下的失落怎樣安放？";
  result.dateMiddle13 = together
    ? "小攤開始收拾，你們沿著水邊慢慢往回走。他提到節目以後，自己並不總有今天這麼多時間。「如果真的相處，可能也會有很普通、甚至沒什麼話說的一天。」他沒有問你能不能接受全部的他，只等你說自己怎麼想。"
    : "午餐後，大家分散去做自己的事。你把晾乾的杯子放回櫃子，還是會想起那個沒有成立的邀請，但沒有人催著你今天就釋懷。旅行搭檔還沒開始選，你還有時間先聽自己。";
  const options = together
    ? [
        [
          "我說我記得幾次真正被聽見的時候，想再了解現在的他。",
          "我問既然互選了，他是不是可以不用再了解其他人。",
          "我說今天想見他是真的，但還不能把未來說成確定。",
        ],
        [
          "我說我想看見他的普通日子，也願意讓他了解我的難相處。",
          "我問如果今天換成別人，他是不是也會說一樣的話。",
          "我說今天很開心，節目外的事希望再多談幾次。",
        ],
      ]
    : [
        [
          "我和留下來的人一起煮午餐，先不打聽任何人的結果。",
          "我想自己坐一會兒，等有力氣再回公共空間。",
          "我把原本想帶去的書拿出來，先照顧好今天的自己。",
        ],
        [
          "我承認自己失望，也提醒自己沒有互選不等於被否定。",
          "我想把還沒說清楚的話留到合適的時候，不追著要答案。",
          "我先不逼自己改變心意，但下一次選擇會重新想。",
        ],
      ];
  const replies = together
    ? [
        [
          "他說有一次你沒有立刻接話，自己卻第一次不怕冷場。「我也記得。」他說。互選沒有替你們說完答案，但這次的理由不是因為不想輸。",
          "他把杯子放下：「今天想和你出去是真的，但我還沒準備好用這個承諾。」你們走在一起，卻得重新確認互選到底答應了多少。",
          "他說自己也想認真過今天，不用先拿以後來證明。你們坐得比剛才近了一點，但還保留著可以慢慢回答的距離。",
        ],
        [
          "他問你說的難相處是哪一件，沒有急著說都能接受。你挑了一件真的可能吵架的小事，他認真想過才回答，這反而讓你比較安心。",
          "他沒有笑著糊弄過去：「我今天在和你說，也希望你先聽我今天的話。」那段安靜裡，你聽見自己的比較又走在了解前面。",
          "他說好，也提了一個還想再問你的問題。今天沒有預訂結局，但你們把下一段談話留了下來。",
        ],
      ]
    : [
        [
          "有人把洗好的菜遞給你，沒有追問你為什麼留下。你終於可以先談火要不要關小一點。",
          "你在沙發另一端坐了一會兒。等自己願意起身時，廚房的人還替你留著一份。",
          "你翻了幾頁才真正看進去。今天沒有照預想發生，但也不是完全空白。",
        ],
        [
          "你沒有立刻好受，卻不再替對方寫一個傷害自己的理由。",
          "你把那句沒說完的話記在心裡，沒有把下一個人的陪伴拿來逼誰回頭。",
          "你仍會想知道答案，但願意承認自己的心意也可以在後面改變。",
        ],
      ];
  for (const [turn, n] of [
    ["a", 0],
    ["b", 1],
  ] as const) {
    for (let i = 0; i < 3; i++) {
      result[`dateOption13${turn}${i}`] = options[n][i];
      result[`dateReply13${turn}${i}`] = replies[n][i];
    }
  }
  const all = { ...facts, ...result };
  for (const d of [2, 3, 10, 13])
    for (const turn of ["a", "b"]) {
      let index = -1;
      try {
        index =
          JSON.parse(
            String(
              state.ui?.kakao?.[`answer:d${d}-date-choice-${turn}`] || "null",
            ),
          )?.optionIndex ?? -1;
      } catch {
        /* Legacy saves have no date turn. */
      }
      const lines = JSON.parse(
        rules?.[`date${d}replies${turn.toUpperCase()}`] || "[]",
      ) as string[];
      result[`dateReply${d}${turn}`] =
        index < 0
          ? ""
          : (lines[index] || "").replace(
              /\{\{(\w+)\}\}/g,
              (_, k) => all[k] || "",
            );
    }
  return result;
}
